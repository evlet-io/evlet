"""Optional PostgreSQL persistence with the same explicit transaction contract."""

from contextlib import contextmanager
import re
import os
import threading
import sqlite3

from .database import Database, Session, ConflictError
from .models import identifier, ValidationError

# Tokenize quoted text before adapting framework SQL. Values remain parameters.
_TOKENS = re.compile(r"'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|[A-Za-z_][A-Za-z_0-9]*|\?|.", re.S)


class Row:
    def __init__(self, names, values):
        self.names, self.items = names, tuple(values)

    def __getitem__(self, key):
        return self.items[key if isinstance(key, int) else self.names.index(key)]

    def __iter__(self): return iter(self.items)
    def __len__(self): return len(self.items)
    def keys(self): return self.names
    def values(self): return self.items


def _row_factory(cursor):
    names = [column.name for column in cursor.description or ()]
    return lambda values: Row(names, values)


class Connection:
    """Adapt the framework's bounded SQL dialect; not a SQLite SQL emulator."""

    def __init__(self, raw, database):
        self.raw, self.database = raw, database

    def execute(self, sql, values=()):
        if sql == 'BEGIN':
            sql = 'BEGIN ISOLATION LEVEL REPEATABLE READ READ ONLY'
        ignore = sql.startswith('INSERT OR IGNORE INTO ')
        if ignore:
            sql = sql.replace('INSERT OR IGNORE INTO ', 'INSERT INTO ', 1) + ' ON CONFLICT DO NOTHING'
        ddl = sql.startswith(('CREATE TABLE', 'ALTER TABLE'))
        tokens = _TOKENS.findall(sql)
        converted = []
        skip_until = -1
        for position, token in enumerate(tokens):
            if position < skip_until:
                continue
            if ddl and tokens[position:position+7] == ['INTEGER', ' ', 'PRIMARY', ' ', 'KEY', ' ', 'AUTOINCREMENT']:
                converted.append('BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
                skip_until = position + 7
                continue
            if token == 'X' and position + 1 < len(tokens) and tokens[position + 1] == "''":
                continue
            if token == "''" and position and tokens[position - 1] == 'X':
                converted.append("''::bytea")
                continue
            if token == '?': token = '%s'
            else:
                if ddl and token.upper() == 'INTEGER': token = 'BIGINT'
                if ddl and token.upper() == 'BLOB': token = 'BYTEA'
                if token == 'instr': token = 'strpos'
                # Psycopg's parameter parser also scans quoted SQL text.
                token = token.replace('%', '%%')
            converted.append(token)
        sql = ''.join(converted)
        match = re.match(r'INSERT INTO ("?[A-Za-z_][A-Za-z_0-9]*"?)', sql)
        generated = set(self.database.registry.models) | {'evlet_users', 'evlet_attachments', 'evlet_events', 'evlet_jobs'}
        returning = match and match[1].strip('"') in generated and ' RETURNING ' not in sql.upper()
        if returning:
            sql += ' RETURNING id'
        if any(isinstance(value, str) and '\x00' in value for value in values):
            raise ValidationError({'_form': 'PostgreSQL text cannot contain NUL characters'})
        cursor = self.raw.execute(sql, tuple(int(v) if type(v) is bool else v for v in values))
        return Cursor(cursor, returning)

    def executemany(self, sql, rows):
        for row in rows:
            self.execute(sql, row)

    def commit(self):
        self.raw.commit()

    def rollback(self):
        self.raw.rollback()


class Cursor:
    def __init__(self, cursor, returning=False):
        self.cursor = cursor
        row = cursor.fetchone() if returning else None
        self.lastrowid = row[0] if row else None
        self.rowcount = cursor.rowcount

    def fetchone(self): return self.cursor.fetchone()
    def fetchall(self): return self.cursor.fetchall()
    def __iter__(self): return iter(self.cursor)


class PostgreSQLDatabase(Database):
    """One dedicated PostgreSQL database, optional psycopg 3 driver.

    Framework write transactions serialize per database, preserving action,
    account, queue, and storage invariants. Independent databases do not share
    locks. Reads use MVCC; this version does not promise parallel tenant writes.
    """

    def __init__(self, dsn, registry, *, migrations=None, timeout=5, max_connections=10):
        try:
            import psycopg
            from psycopg_pool import ConnectionPool
        except ImportError:
            raise RuntimeError('Install evlet[postgres] to use PostgreSQL') from None
        if not isinstance(dsn, str) or not dsn:
            raise ValueError('Configure a PostgreSQL connection string')
        if type(timeout) is not int or not 1 <= timeout <= 300:
            raise ValueError('Use a timeout between 1 and 300 seconds')
        if type(max_connections) is not int or not 1 <= max_connections <= 100:
            raise ValueError('Use between 1 and 100 pooled connections')
        for table, model in registry.models.items():
            for name in (table, *model.__fields__):
                if len(name.encode()) > 63:
                    raise ValueError('PostgreSQL identifiers cannot exceed 63 bytes')
        self._dsn, self.driver, self.timeout = dsn, psycopg, timeout
        self._pool_factory = ConnectionPool
        self._pool = None
        self._pool_lock = threading.Lock()
        self._pid = os.getpid()
        self.max_connections = max_connections
        self.registry = registry
        self.migrations = None if migrations is None else tuple(migrations)

    def _configure(self, raw):
        raw.execute("SELECT set_config('search_path', 'public,pg_catalog', false), "
                    "set_config('statement_timeout', %s, false), "
                    "set_config('lock_timeout', %s, false), "
                    "set_config('idle_in_transaction_session_timeout', %s, false)",
                    (str(self.timeout * 1000),) * 3)

    def _reset(self, raw):
        raw.execute('DISCARD ALL')
        self._configure(raw)

    def _connections(self):
        if os.getpid() != self._pid:
            raise RuntimeError('Construct PostgreSQLDatabase inside each worker process')
        with self._pool_lock:
            if self._pool is None:
                self._pool = self._pool_factory(
                    self._dsn, min_size=0, max_size=self.max_connections,
                    max_waiting=100, timeout=self.timeout, open=True,
                    name='evlet', configure=self._configure, reset=self._reset,
                    kwargs={'autocommit': True, 'connect_timeout': self.timeout,
                            'row_factory': _row_factory, 'prepare_threshold': None})
            return self._pool

    def close(self):
        """Release pooled connections after requests and workers have stopped."""
        with self._pool_lock:
            if self._pool is not None:
                self._pool.close()
                self._pool = None

    @contextmanager
    def _connection(self):
        try:
            with self._connections().connection() as raw:
                try:
                    yield Connection(raw, self)
                finally:
                    raw.rollback()
        except self.driver.DataError:
            raise ValidationError({'_form': 'Value cannot be stored by PostgreSQL'}) from None
        except self.driver.IntegrityError:
            raise ConflictError('A unique value or linked record constraint was violated') from None
        except self.driver.Error:
            # Never put connection strings, SQL values, or server details in HTTP errors.
            raise sqlite3.OperationalError('PostgreSQL operation failed') from None

    @contextmanager
    def transaction(self):
        with self._connection() as connection:
            try:
                connection.execute('BEGIN ISOLATION LEVEL READ COMMITTED')
                connection.execute('SELECT pg_advisory_xact_lock(1163283540)')
                yield Session(connection, self.registry)
                connection.commit()
            except BaseException:
                connection.rollback()
                raise

    def owns(self, session):
        return isinstance(session.connection, Connection) and session.connection.database is self

    def columns(self, connection, table):
        identifier(table)
        return {row[0] for row in connection.execute(
            "SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name=?", (table,))}

    def initialize(self):
        from .postgres_schema import initialize
        initialize(self)

    def migrate(self, migrations):
        from .postgres_schema import migrate
        return migrate(self, migrations)
