"""PostgreSQL schema inspection and atomic, explicit migrations."""

import hashlib
import json
import sqlite3

from .fields import Link, Reference, Text
from .models import identifier, storage_name
from .migrations import (Applied, SchemaError, AddField, AddIndex, AddTable, AlterField, CreateModel, DropField, RenameField,
                         Recompute, RetireField, RunData, retired_columns, step_arguments, destructive, maintenance_steps, run_data,
                         _metadata, _definition, _migration_plan, _history, _same, _comparable, mismatch, link_target, plan_from,
                         _planned_definition, _recompute, recomputes, index_columns, stored_columns, app_fields, instance_columns,
                         standard_fields, leftover_standard)
from .naming import declared_name, standard


def validate_indexes(registry):
    # 500 Unicode characters occupy at most 2,000 UTF-8 bytes, leaving room
    # for B-tree tuple overhead on standard 8 KiB PostgreSQL pages.
    for table, model in registry.models.items():
        for name, field in model.__fields__.items():
            if isinstance(field, Text) and (field.index or field.unique) and field.max_length > 500:
                raise SchemaError(f'{table}.{name}: PostgreSQL indexed text requires max_length <= 500')


def column(name, field):
    """Column definitions for one field; most fields have one, a Reference has two."""
    return [f'{identifier(name)} {"BIGINT" if sql_type == "INTEGER" else sql_type}' + (' NOT NULL' if field.required else '')
            for name, sql_type in field.columns(name)]


def relation_name(db, kind, key):
    digest = hashlib.sha256(key.encode()).hexdigest()[:32]
    base = f'evlet_{kind}_' + digest
    name, suffix = base, 1
    while db.execute("SELECT 1 FROM pg_class c JOIN pg_namespace n ON n.oid=c.relnamespace "
                    "WHERE n.nspname='public' AND c.relname=?", (name,)).fetchone():
        suffix += 1
        name = f'{base}_{suffix}'
    return name


def index(db, table, field, unique=False, columns=None):
    # A field rename preserves its index name; the old field name may be reused.
    name = relation_name(db, 'idx', f'{table}:{field}:{unique}')
    covered = ', '.join(identifier(column) for column in (columns or (field,)))
    db.execute(f'CREATE {"UNIQUE " if unique else ""}INDEX {identifier(name)} ON {identifier(table)} ({covered})')


def sequence_index(db, table, name, field):
    from .sequences import index_sql
    db.execute(index_sql(relation_name(db, 'idx', f'{table}:{name}:sequence'), table, name, field))


def links(db, table, model):
    for name, field in model.__fields__.items():
        if isinstance(field, Link):
            db.execute(f'ALTER TABLE {identifier(table)} ADD FOREIGN KEY ({identifier(name)}) REFERENCES {identifier(link_target(field))}(id)')


def reserve_id_names(db, table):
    sequence = db.execute('SELECT relname FROM pg_class WHERE oid=pg_get_serial_sequence(?, ?)::regclass',
                          (identifier(table), 'id')).fetchone()
    primary = db.execute('SELECT c.relname FROM pg_index i JOIN pg_class c ON c.oid=i.indexrelid '
                         'WHERE i.indrelid=?::regclass AND i.indisprimary', (identifier(table),)).fetchone()
    for kind, prefix, row in (('SEQUENCE', 'seq', sequence), ('INDEX', 'pk', primary)):
        if row and not row[0].startswith('evlet_'):
            name = relation_name(db, prefix, table)
            db.execute(f'ALTER {kind} {identifier(row[0])} RENAME TO {identifier(name)}')


def create(db, table, model):
    """A table for a model; see migrations._create for the standard columns."""
    framework = not declared_name(model)
    fields = {name: field for name, field in model.__fields__.items() if framework or not standard(field)}
    columns = ['id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY']
    columns.extend(sql for name, field in fields.items() for sql in column(name, field))
    db.execute(f'CREATE TABLE {identifier(table)} ({", ".join(columns)})')
    reserve_id_names(db, table)
    for name, field in fields.items():
        if field.index or field.unique:
            index(db, table, name, field.unique, index_columns(name, field))
        if field.kind == 'sequence':
            sequence_index(db, table, name, field)


def tables(db):
    return {r[0] for r in db.execute("SELECT tablename FROM pg_tables WHERE schemaname='public' AND left(tablename,6)<>'evlet_'")}


def check(db, registry, rows=False):
    added, retired = instance_columns(db, postgres=True), retired_columns(db, postgres=True)
    for table, model in registry.models.items():
        columns = db.execute("SELECT column_name,data_type,is_nullable,is_identity FROM information_schema.columns WHERE table_schema='public' AND table_name=?", (table,)).fetchall()
        names = [r[0] for r in columns]
        skip = added.get(table, set()) | {column for field in retired.get(table, ()) for column in stored_columns(names, field)} \
            | leftover_standard(model, {r[0]: r[2] == 'YES' for r in columns})
        actual = {r[0]: (r[1], r[2] == 'NO', r[3] == 'YES') for r in columns if r[0] not in skip}
        # A table made before records had standard columns gets them from framework step 0003 (evlet migrate).
        framework = standard_fields(model)
        present = {key for key in framework if key in names}
        if present and present != set(framework):
            raise SchemaError(f'{table}: the standard name and title columns are incomplete; run evlet migrate')
        expected = {'id': ('bigint', True, True), **{
            name: ('bigint' if sql_type == 'INTEGER' else 'text', field.required, False)
            for key, field in app_fields(model).items() for name, sql_type in field.columns(key)},
            **({key: ('text', False, False) for key in framework} if present else {})}
        if actual != expected:
            raise SchemaError(f'{table}: database columns differ from models')
        foreign = db.execute('''SELECT a.attname, target.relname, ta.attname, c.confdeltype, tn.nspname, cardinality(c.conkey), cardinality(c.confkey), c.convalidated
            FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid
            JOIN pg_namespace n ON n.oid=t.relnamespace
            JOIN pg_class target ON target.oid=c.confrelid JOIN pg_namespace tn ON tn.oid=target.relnamespace
            JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=c.conkey[1]
            JOIN pg_attribute ta ON ta.attrelid=target.oid AND ta.attnum=c.confkey[1]
            WHERE n.nspname='public' AND t.relname=? AND c.contype='f' ''', (table,))
        if {tuple(r.values()) for r in foreign if r[0] not in skip} != {(name, storage_name(field.target), 'id', 'a', 'public', 1, 1, True) for name, field in app_fields(model).items() if isinstance(field, Link)}:
            raise SchemaError(f'{table}: foreign keys differ from models')
        indexes = db.execute('''SELECT i.indisunique,i.indisprimary,array_agg(a.attname ORDER BY k.ordinality) AS fields
            FROM pg_index i JOIN pg_class t ON t.oid=i.indrelid JOIN pg_namespace n ON n.oid=t.relnamespace
            CROSS JOIN LATERAL unnest(i.indkey) WITH ORDINALITY AS k(num,ordinality)
            JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=k.num
            WHERE n.nspname='public' AND t.relname=? AND i.indpred IS NULL AND i.indisvalid
            GROUP BY i.indexrelid,i.indisunique,i.indisprimary''', (table,)).fetchall()
        if {tuple(r['fields']) for r in indexes if r['indisprimary']} != {('id',)}:
            raise SchemaError(f'{table}: primary key differs from models')
        if {tuple(r['fields']) for r in indexes if r['indisunique'] and not r['indisprimary'] and not set(r['fields']) & skip} \
                != {(name,) for name, field in model.__fields__.items() if field.unique and (name in present or not standard(field))}:
            raise SchemaError(f'{table}: unique constraints differ from models')
        indexed = {tuple(r['fields']) for r in indexes}
        if any(index_columns(name, field) not in indexed for name, field in model.__fields__.items() if field.index):
            raise SchemaError(f'{table}: an explicit index migration is required')
        if any(field.kind == 'sequence' for field in model.__fields__.values()):
            partial = db.execute('''SELECT array_agg(a.attname ORDER BY k.ordinality) AS fields
                FROM pg_index i JOIN pg_class t ON t.oid=i.indrelid JOIN pg_namespace n ON n.oid=t.relnamespace
                CROSS JOIN LATERAL unnest(i.indkey) WITH ORDINALITY AS k(num,ordinality)
                JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=k.num
                WHERE n.nspname='public' AND t.relname=? AND i.indpred IS NOT NULL AND i.indisunique AND i.indisvalid
                GROUP BY i.indexrelid''', (table,)).fetchall()
            if any((*field.scope, name) not in {tuple(r['fields']) for r in partial}
                   for name, field in model.__fields__.items() if field.kind == 'sequence'):
                raise SchemaError(f'{table}: a Sequence field is missing its unique index')
        if rows:
            # Server cursor keeps migration validation memory bounded on large tables.
            with db.raw.cursor(name='evlet_schema_validation') as cursor:
                cursor.execute(f'SELECT * FROM {identifier(table)}')
                for row in cursor:
                    model._from_row(row)


def save(db, registry):
    db.execute('INSERT INTO evlet_schema(id,definition) VALUES(1,?) ON CONFLICT(id) DO UPDATE SET definition=excluded.definition', (_definition(registry),))


def bootstrap(db, registry):
    for table, model in registry.models.items(): create(db, table, model)
    for table, model in registry.models.items(): links(db, table, model)


def initialize(database):
    validate_indexes(database.registry)
    plan = None if database.migrations is None else _migration_plan(database.migrations)
    with database.transaction() as tx:
        db = tx.connection
        fresh = not tables(db)
        _metadata(db)
        saved = db.execute('SELECT definition FROM evlet_schema WHERE id=1').fetchone()
        if saved and not _same(saved[0], database.registry):
            raise SchemaError('Model definitions changed; run explicit migrations before startup')
        baseline = False
        if plan is not None:
            migrations, checksums = plan
            history = _history(db, migrations, checksums)
            if history and len(history) != len(migrations):
                raise SchemaError('Unapplied migration history; run explicit migrations before startup')
            baseline = not history
        if fresh: bootstrap(db, database.registry)
        check(db, database.registry, rows=not saved or baseline)
        if baseline:
            db.executemany('INSERT INTO evlet_migrations(position,name,checksum) VALUES(?,?,?)',
                           [(i+1, m.name, checksums[i]) for i,m in enumerate(migrations)])
        if any(getattr(model, 'confirmable', False) for model in database.registry.models.values()):
            from .lifecycle import ensure_tables
            ensure_tables(db, postgres=True)
        save(db, database.registry)


def columns_of(db, table):
    return {row[0] for row in db.execute("SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name=?", (table,))}


def apply(db, op, *arguments):
    if isinstance(op, RetireField):
        for name in stored_columns(columns_of(db, op.table), op.name):
            db.execute(f'ALTER TABLE {identifier(op.table)} ALTER COLUMN {identifier(name)} DROP NOT NULL')
            # A retired Link stops guarding its target: drop the column's foreign key, as SQLite does.
            for row in db.execute("SELECT c.conname FROM pg_constraint c JOIN pg_class t ON t.oid=c.conrelid "
                                  "JOIN pg_namespace n ON n.oid=t.relnamespace JOIN pg_attribute a ON a.attrelid=t.oid AND a.attnum=ANY(c.conkey) "
                                  "WHERE n.nspname='public' AND t.relname=? AND c.contype='f' AND a.attname=?", (op.table, name)).fetchall():
                db.execute(f'ALTER TABLE {identifier(op.table)} DROP CONSTRAINT {identifier(row[0])}')
        db.execute('CREATE TABLE IF NOT EXISTS evlet_retired_fields (model TEXT NOT NULL, name TEXT NOT NULL, '
                   'definition TEXT NOT NULL, PRIMARY KEY (model, name))')
        db.execute('INSERT INTO evlet_retired_fields (model, name, definition) VALUES (?, ?, ?)',
                   (op.table, op.name, json.dumps(arguments[0] if arguments else {}, sort_keys=True)))
    elif isinstance(op, DropField):
        op._retired(db, postgres=True)
        for name in stored_columns(columns_of(db, op.table), op.name):
            # Indexes and the foreign key on the column go with it.
            db.execute(f'ALTER TABLE {identifier(op.table)} DROP COLUMN {identifier(name)}')
        db.execute('DELETE FROM evlet_retired_fields WHERE model = ? AND name = ?', (op.table, op.name))
    elif isinstance(op, (AlterField, RunData)):
        op.apply(db, *arguments)  # Values only; RunData runs after the batch's structural changes.
    elif isinstance(op, (CreateModel, AddTable)):
        model = op.model() if isinstance(op, AddTable) else op.model
        table = storage_name(model)
        create(db, table, model)
        links(db, table, model)
    elif isinstance(op, AddIndex):
        columns = {row[0] for row in db.execute("SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name=?", (op.table,))}
        index(db, op.table, op.field, op.unique, stored_columns(columns, op.field))
    elif isinstance(op, RenameField):
        op.apply(db, {row[0] for row in db.execute("SELECT column_name FROM information_schema.columns WHERE table_schema='public' AND table_name=?", (op.table,))})
    elif isinstance(op, Recompute):
        pass  # Recalculated after the batch's structural changes.
    elif isinstance(op, AddField):
        values = op.field.to_columns(op.value())
        if isinstance(op.field, (Link, Reference)) and any(value is not None for value in values):
            raise SchemaError('Add nullable Link and Reference fields with a null backfill')
        for sql, value in zip(column(op.name, op.field), values):
            # Psycopg literals are used only for DDL, which cannot bind defaults.
            literal = db.database.driver.sql.Literal(value).as_string(db.raw)
            db.execute(f'ALTER TABLE {identifier(op.table)} ADD COLUMN {sql} DEFAULT {literal}')
        if isinstance(op.field, Link):
            db.execute(f'ALTER TABLE {identifier(op.table)} ADD FOREIGN KEY ({identifier(op.name)}) REFERENCES {identifier(link_target(op.field))}(id)')
        if op.field.index or op.field.unique: index(db, op.table, op.name, op.field.unique, index_columns(op.name, op.field))
        if op.field.kind == 'sequence': sequence_index(db, op.table, op.name, op.field)


def migrate(database, migrations, *, recompute_posted=False, allow_destructive=False, allow_maintenance=False):
    validate_indexes(database.registry)
    migrations, checksums = _migration_plan(migrations)
    try:
        with database.transaction(timeout=database.migration_timeout) as tx:
            db = tx.connection
            fresh = not tables(db)
            _metadata(db)
            history = _history(db, migrations, checksums)
            saved = db.execute('SELECT definition FROM evlet_schema WHERE id=1').fetchone()
            if not fresh and not saved:
                raise SchemaError('Initialize the legacy database with its original models before migrating')
            pending = migrations[len(history):]
            steps = {}
            if saved and (history or not _same(saved[0], database.registry)):
                planned = _planned_definition(saved[0], pending, steps)
                if _comparable(planned) != _comparable(database.registry.schema()):
                    raise mismatch(planned, database.registry.schema())
                destructive(pending, allow_destructive)
                maintenance_steps(pending, allow_maintenance)
            baseline = not history and saved and _same(saved[0], database.registry)
            if fresh:
                bootstrap(db, database.registry)
            else:
                # Existing releases used PostgreSQL's table-derived names. Move
                # owned objects before a new model can reuse one of those names.
                for table in tables(db) & database.registry.models.keys():
                    reserve_id_names(db, table)
            for position, migration in enumerate(pending, len(history)+1):
                if not fresh and not baseline:
                    for operation in migration.operations: apply(db, operation, *step_arguments(operation, steps))
                    run_data(db, database.registry, migration)
                db.execute('INSERT INTO evlet_migrations(position,name,checksum) VALUES(?,?,?)', (position, migration.name, checksums[position-1]))
            if any(getattr(model, 'confirmable', False) for model in database.registry.models.values()):
                from .lifecycle import ensure_tables
                ensure_tables(db, postgres=True)
            applied = Applied(item.name for item in pending)
            if not fresh and not baseline:
                applied.skipped, applied.posted = _recompute(db, database.registry, recomputes(pending), lambda connection: connection.execute(
                    "SELECT 1 FROM pg_tables WHERE schemaname='public' AND tablename='evlet_calculation_versions'").fetchone() is not None,
                    postgres=True, include_posted=recompute_posted)
            # The batch ends with the models' standard name and title columns (see migrations.migrate).
            from .naming import add_columns, fill_titles
            for table, model in database.registry.models.items():
                add_columns(db, True, table, model)
                fill_titles(db, table, model)
            check(db, database.registry, rows=True)
            save(db, database.registry)
            return applied
    except (sqlite3.Error, ValueError, TypeError) as exc:
        if isinstance(exc, SchemaError): raise
        raise SchemaError('Migration rolled back') from exc


def plan(database, migrations):
    """What migrate(database, migrations) would do. Only reads, in a transaction that changes nothing."""
    validate_indexes(database.registry)
    with database.transaction() as tx:
        db = tx.connection
        def exists(name):
            return db.execute("SELECT 1 FROM pg_tables WHERE schemaname='public' AND tablename=?", (name,)).fetchone() is not None
        saved = db.execute('SELECT definition FROM evlet_schema WHERE id=1').fetchone() if exists('evlet_schema') else None
        history = [(row[0], row[1]) for row in db.execute('SELECT name,checksum FROM evlet_migrations ORDER BY position')] \
            if exists('evlet_migrations') else []
        return plan_from(saved and saved[0], history, migrations, database.registry, tables=bool(tables(db)))
